export function getCountryLabel(
  code: string | null | undefined,
  t: (descriptor: ReturnType<typeof msg>) => string,
): string {
  if (!code) return '';
  const upper = code.toUpperCase();
  const descriptor = COUNTRY_LABELS[upper];
  return descriptor ? t(descriptor) : upper;
}
